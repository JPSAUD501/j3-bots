import * as Schema from "effect/Schema";
import * as SchemaGetter from "effect/SchemaGetter";

export const NonNegativeInt = Schema.Int.check(Schema.isGreaterThanOrEqualTo(0));
export const PositiveInt = Schema.Int.check(Schema.isGreaterThanOrEqualTo(1));

/** The longest `Label`. */
export const MAX_LABEL_LENGTH = 200;

/** Text a person reads: a name, a label, a line of status. */
export const Label = Schema.String.check(
  Schema.isMinLength(1),
  Schema.isMaxLength(MAX_LABEL_LENGTH),
);

/** The longest id of any kind. */
export const MAX_ID_LENGTH = 128;

const id = Schema.String.check(Schema.isMinLength(1), Schema.isMaxLength(MAX_ID_LENGTH));

export const BotId = id.pipe(Schema.brand("BotId"));
export type BotId = typeof BotId.Type;

export const RoomId = id.pipe(Schema.brand("RoomId"));
export type RoomId = typeof RoomId.Type;

export const EntryId = id.pipe(Schema.brand("EntryId"));
export type EntryId = typeof EntryId.Type;

export const RoutineId = id.pipe(Schema.brand("RoutineId"));
export type RoutineId = typeof RoutineId.Type;

export const RoutineRunId = id.pipe(Schema.brand("RoutineRunId"));
export type RoutineRunId = typeof RoutineRunId.Type;

export const AttachmentId = id.pipe(Schema.brand("AttachmentId"));
export type AttachmentId = typeof AttachmentId.Type;

/** A named group of bots in the operator's roster. */
export const SectionId = id.pipe(Schema.brand("SectionId"));
export type SectionId = typeof SectionId.Type;

export const DeviceId = id.pipe(Schema.brand("DeviceId"));
export type DeviceId = typeof DeviceId.Type;

/** A provider the engine offers, such as one Claude Code sign-in. */
export const ProviderId = id.pipe(Schema.brand("ProviderId"));
export type ProviderId = typeof ProviderId.Type;

/** One step of a turn's work: a command, an edit, a search, a delegated task. */
export const WorkStepId = Schema.String.check(Schema.isMinLength(1), Schema.isMaxLength(256)).pipe(
  Schema.brand("WorkStepId"),
);
export type WorkStepId = typeof WorkStepId.Type;

/**
 * An image a step of a bot's work looked at, as the server names it: never
 * its path. Its bytes are served at `GET /work-images/<id>` (see `http.ts`).
 */
export const WorkImageId = id.pipe(Schema.brand("WorkImageId"));
export type WorkImageId = typeof WorkImageId.Type;

/** A model slug within one provider. */
export const ModelId = id.pipe(Schema.brand("ModelId"));
export type ModelId = typeof ModelId.Type;

/**
 * A level of reasoning effort, as the engine names it for a model, such as
 * `low`, `high` or `xhigh`. Which levels a model takes is the engine's report
 * of it (`ProviderStatus.models`), and differs by provider and model.
 */
export const EffortLevel = id.pipe(Schema.brand("EffortLevel"));
export type EffortLevel = typeof EffortLevel.Type;

/**
 * Generated by the client for every command and reused when the same command is
 * retried. The server applies a command id once: a retry returns the first result.
 */
export const CommandId = id.pipe(Schema.brand("CommandId"));
export type CommandId = typeof CommandId.Type;

/**
 * Where an entry sits in its conversation or room. Assigned once, when the entry
 * is created, and never changed: entries sort by it, and an entry that is
 * updated later keeps its place. Only comparable within one target.
 */
export const EntryOrder = NonNegativeInt.pipe(Schema.brand("EntryOrder"));
export type EntryOrder = typeof EntryOrder.Type;

/**
 * A position in the server's change history. Says how far a subscriber has
 * applied changes, never where an entry sorts (that is `EntryOrder`). Only
 * comparable within the subscription that produced it.
 */
export const Sequence = NonNegativeInt.pipe(Schema.brand("Sequence"));
export type Sequence = typeof Sequence.Type;

/**
 * A string none of `known` is: a value a newer server sends that this build
 * cannot read. A known value never passes, so a value of a kind this build
 * knows that fails to decode still fails, instead of passing as unknown.
 */
export const UnknownLiteral = (known: ReadonlyArray<string>) =>
  Schema.String.check(
    Schema.makeFilter(
      (value: string) => !known.includes(value) || "a value this build does not know",
    ),
  );

/**
 * `known`, open to values added after this build: any other string decodes
 * as `unknown`. Only for what a client receives and can show without
 * understanding (docs/architecture/clients.md, "Protocol compatibility").
 */
export const OpenLiterals = <const L extends ReadonlyArray<string>>(known: L) =>
  Schema.Union([
    Schema.Literals(known),
    UnknownLiteral(known).pipe(
      Schema.decodeTo(Schema.Literal("unknown"), {
        decode: SchemaGetter.transform(() => "unknown" as const),
        encode: SchemaGetter.transform((value: string) => value),
      }),
    ),
  ]);

/** The languages the interface is written in, and a push to a device can be. */
export const LANGUAGES = ["en", "pt-BR"] as const;
export const Language = Schema.Literals(LANGUAGES);
export type Language = typeof Language.Type;

/**
 * A skill's name: lowercase letters, digits and inner hyphens, at most 64
 * characters, the names harnesses list skills under and the Agent Skills
 * format gives them, a connector's too. A bot's own skill is the folder of
 * that name in its workspace: the name holds no separator or dot, so it can
 * never name a place outside the bot's skills.
 */
export const SkillName = Schema.String.check(
  Schema.isPattern(/^[a-z0-9](?:[a-z0-9-]{0,62}[a-z0-9])?$/),
);
export type SkillName = typeof SkillName.Type;
