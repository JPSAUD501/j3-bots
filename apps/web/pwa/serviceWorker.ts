import { HTTP_PATHS } from "@j3-bots/contracts";
import { NOTIFICATION_CLICK } from "./notificationClick.ts";

/**
 * The service worker's source, for one build. It exists so the installed app
 * opens with no connection: it keeps the app shell (the page, its scripts,
 * styles, fonts and icons) and nothing else.
 *
 * - A page load goes to the network first, so a new build shows at once; only
 *   when the network fails, the server answers with an error of its own (a
 *   5xx, as from a proxy whose server is down), or the whole page, headers
 *   and body, does not arrive within `NAVIGATION_WAIT_MS`, does the kept
 *   page answer.
 * - A file of the shell is answered from the kept copy; its name carries its
 *   content's hash, so the copy is never stale.
 * - The API, the RPC socket and attachments are never answered or kept: they
 *   carry the operator's data, and they always go to the server.
 *
 * Each build keeps its shell under its own cache name, and a new worker
 * deletes the caches of older builds once it takes over.
 *
 * It also shows the app's notifications, where a page cannot show them itself
 * (Android's browsers), and opens what a click on one asks for: it focuses a
 * window of the app, the focused one first, then a visible one, and tells it
 * which conversation or room to open; with no window, it opens one there.
 */
/**
 * How long a page load waits for the network before the kept page answers: a
 * server or a proxy that takes the request and never answers, or sends the
 * headers and then stops, would otherwise leave the installed app blank.
 */
const NAVIGATION_WAIT_MS = 4000;

export function serviceWorkerSource(version: string, shell: ReadonlyArray<string>): string {
  const config = {
    cache: `j3-shell-${version}`,
    shell,
    page: "/index.html",
    navigationWait: NAVIGATION_WAIT_MS,
    notificationClick: NOTIFICATION_CLICK,
    // Every API path sits under /api/, beside the socket and attachments.
    neverCached: ["/api/", HTTP_PATHS.rpc, HTTP_PATHS.attachments],
  };
  return `// SPDX-License-Identifier: AGPL-3.0-or-later
// Generated by apps/web/pwa/serviceWorker.ts. Keeps the app shell for offline launch.
"use strict";
const CONFIG = ${JSON.stringify(config)};
const SHELL = new Set(CONFIG.shell);

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CONFIG.cache).then((cache) => cache.addAll(CONFIG.shell)).then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((key) => key.startsWith("j3-shell-") && key !== CONFIG.cache)
            .map((key) => caches.delete(key)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

const keptPage = () => caches.match(CONFIG.page, { cacheName: CONFIG.cache });

// The page from the network, headers and body, within CONFIG.navigationWait,
// or a failure. A copy of the answer is read to its end, and the answer itself
// is what the page gets, its headers, status and URL as the network gave them.
// Once the wait is over, a body still arriving is cancelled, and so is the body
// of an answer whose headers come later, which stops its download. The request
// itself goes as the browser made it: one sent with an abort signal would no
// longer be a page load to the server or a proxy, so one with no answer yet is
// left to end on its own.
const loadPage = (request) =>
  new Promise((resolve, reject) => {
    let late = false;
    let answer = null;
    let copy = null;
    const timer = setTimeout(() => {
      late = true;
      reject(new Error("The page did not arrive in time"));
      copy?.cancel();
      answer?.body?.cancel();
    }, CONFIG.navigationWait);
    fetch(request)
      .then(async (got) => {
        if (late) {
          got.body?.cancel();
          return got;
        }
        answer = got;
        if (got.body !== null) {
          copy = got.clone().body.getReader();
          while (!(await copy.read()).done);
        }
        return got;
      })
      .then(resolve, reject)
      .finally(() => clearTimeout(timer));
  });

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (CONFIG.neverCached.some((prefix) => url.pathname.startsWith(prefix))) return;
  if (request.mode === "navigate") {
    event.respondWith(
      loadPage(request).then(
        (response) =>
          response.status >= 500 ? keptPage().then((page) => page ?? response) : response,
        () => keptPage().then((page) => page ?? Response.error()),
      ),
    );
    return;
  }
  if (SHELL.has(url.pathname)) {
    event.respondWith(
      caches
        .match(url.pathname, { cacheName: CONFIG.cache })
        .then((kept) => kept ?? fetch(request)),
    );
  }
});

// A notification the app showed carries { target, url }: the conversation or
// room it is about, and that page's path on this origin.
self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const data = event.notification.data;
  if (data === null || typeof data !== "object" || typeof data.url !== "string") return;
  const url = new URL(data.url, self.location.origin);
  if (url.origin !== self.location.origin) return;
  event.waitUntil(
    self.clients.matchAll({ type: "window", includeUncontrolled: true }).then((windows) => {
      const open =
        windows.find((client) => client.focused) ??
        windows.find((client) => client.visibilityState === "visible") ??
        windows[0];
      if (open === undefined) return self.clients.openWindow(url.href);
      return open
        .focus()
        .then((focused) =>
          focused.postMessage({ type: CONFIG.notificationClick, target: data.target }),
        );
    }),
  );
});
`;
}
